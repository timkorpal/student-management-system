from datetime import date, datetime

from sqlalchemy import Boolean, Date, DateTime, String, func
from sqlalchemy.orm import Mapped, mapped_column

from database import Base

"""
SQLAlchemy database models for the Students API.

This module defines the database tables and relationships used by the
application. The Students model represents enrolled students and stores
their identifying information, contact details, enrollment status,
major, and record timestamps.
"""

class Student(Base):
    """
    Represents a student enrolled in the system.

    Each student has a unique student ID and email address along with
    contact information, major, enrollment status, and enrollment date.
    """

    __tablename__ = "students"

# Primary key automatically generated by PostgreSQL.
    id: Mapped[int] = mapped_column(
        primary_key=True
    )

    # Identifier used when communicating with external partners.
    # Example: PARTNER-001
    student_id: Mapped[str | None] = mapped_column(
        String(5),
        unique=True,
        nullable=True,
        index=True
    )

    # Student's first name.
    first_name: Mapped[str] = mapped_column(
        String(100),
        nullable=False
    )

    # Student's last name.
    last_name: Mapped[str] = mapped_column(
        String(100),
        nullable=False
    )

    # Email must be unique so the same Student
    # cannot be registered multiple times.
    email: Mapped[str] = mapped_column(
        String(255),
        unique=True,
        nullable=False,
        index=True
    )

    # Phone numbers are stored as strings because they
    # may contain formatting characters such as +, -, or ().
    phone: Mapped[str] = mapped_column(
        String(30),
        nullable=False
    )


    # Student's last name.
    major: Mapped[str] = mapped_column(
        String(50),
        nullable=False
    )

    # True = actively enrolled
    # False = inactive / no longer enrolled
    status: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=True
    )


    # Date the student enrolled.
    enrollment_date: Mapped[date] = mapped_column(
        Date,
        nullable=False
    )


    # Date/time the database record was created.
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now()
    )


    # Date/time the database record was last updated.
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now()
    )
        