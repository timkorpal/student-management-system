"""
Pydantic schemas for the Students API.

These schemas define and validate the data received by and
returned from the API.
"""

from datetime import date, datetime

from pydantic import BaseModel, ConfigDict, EmailStr, Field


class StudentCreate(BaseModel):
    """
    Request schema used when creating a new student.

    The student ID and timestamps are generated by the backend
    and therefore are not included in the request body.
    """

    first_name: str = Field(
        min_length=1,
        max_length=100
    )

    last_name: str = Field(
        min_length=1,
        max_length=100
    )

    email: EmailStr

    phone: str = Field(
        pattern=r"^\d{3}-\d{3}-\d{4}$",
        examples=["480-323-5128"]
    )

    major: str = Field(
        min_length=2,
        max_length=100
    )

    status: bool = True

    enrollment_date: date


class StudentResponse(BaseModel):
    """
    Response schema returned by the API for a student.
    """

    id: int
    student_id: str

    first_name: str
    last_name: str
    email: EmailStr
    phone: str
    major: str
    status: bool

    enrollment_date: date

    created_at: datetime
    updated_at: datetime

    # Allows Pydantic to create the response from
    # SQLAlchemy model attributes.
    model_config = ConfigDict(from_attributes=True)


class StudentUpdate(BaseModel):
    first_name: str | None = Field(
        default=None,
        min_length=1,
        max_length=100
    )

    last_name: str | None = Field(
        default=None,
        min_length=1,
        max_length=100
    )

    email: EmailStr | None = None

    phone: str | None = Field(
        default=None,
        pattern=r"^\d{3}-\d{3}-\d{4}$"
    )

    major: str | None = Field(
        default=None,
        min_length=2,
        max_length=100
    )

    status: bool | None = None

    enrollment_date: date | None = None